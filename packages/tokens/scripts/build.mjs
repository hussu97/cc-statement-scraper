// Generates platform artifacts from tokens.json:
//   dist/tokens.css   — CSS custom properties (light + dark) and a Tailwind v4 @theme block
//   dist/chart.js     — chart palette for JS charts
//   dist/chart.d.ts   — TypeScript declarations for dist/chart.js
//   ../../apps/ios/LedgerKit/Sources/LedgerKit/Theme/Tokens.swift — the same values for SwiftUI
// `--check` (CI) regenerates everything in memory and writes nothing. It fails only when a
// COMMITTED output (Tokens.swift) differs from what tokens.json produces. dist/ is gitignored
// and rebuilt by `build` (the web app's pre-scripts), so it is never compared: the check is
// deterministic from a clean clone.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const t = JSON.parse(readFileSync(resolve(root, "tokens.json"), "utf8"));
const check = process.argv.includes("--check");

const vars = (obj, prefix) =>
  Object.entries(obj)
    .filter(([k]) => !k.startsWith("$"))
    .map(([k, v]) => `  --${prefix}${k}: ${v};`)
    .join("\n");

const css = `/* GENERATED by packages/tokens/scripts/build.mjs — edit tokens.json instead. */
:root {
${vars(t.color.light, "color-")}
${vars(t.chart.light, "chart-")}
${vars(t.radius, "radius-")}
${vars(t.space, "space-")}
  --font-display: ${t.font.display};
  --font-sans: ${t.font.sans};
  --font-mono: ${t.font.mono};
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(t.color.dark, "color-").replace(/^/gm, "  ")}
${vars(t.chart.dark, "chart-").replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${vars(t.color.dark, "color-")}
${vars(t.chart.dark, "chart-")}
  color-scheme: dark;
}
`;

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const hex = (h) => {
  const n = parseInt(h.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((x) => (x / 255).toFixed(4)).join(", ");
};
const swiftPairs = (light, dark) =>
  Object.keys(light)
    .filter((k) => !k.startsWith("$"))
    .map((k) => {
      const name = /^[0-9]/.test(camel(k)) ? "c" + camel(k) : camel(k);
      return `    public static let ${name} = Color(light: (${hex(light[k])}), dark: (${hex(dark[k])}))`;
    })
    .join("\n");

const swift = `// GENERATED by packages/tokens/scripts/build.mjs — edit packages/tokens/tokens.json instead.
import SwiftUI
#if canImport(UIKit)
import UIKit
#elseif canImport(AppKit)
import AppKit
#endif

public enum Palette {
${swiftPairs(t.color.light, t.color.dark)}
}

public enum ChartPalette {
${swiftPairs(t.chart.light, t.chart.dark)}

    /// Resolve a category's stable colour token ("cat-1" … "cat-12").
    public static func color(for token: String?) -> Color {
        switch token {
${Object.keys(t.chart.light)
  .filter((k) => k.startsWith("cat-"))
  .map((k) => `        case "${k}": return ${"c" + camel(k).replace(/^cat/, "Cat")}`)
  .join("\n")
  .replace(/cCat(\d+)/g, "cat$1")}
        default: return uncategorized
        }
    }
}

public enum Metrics {
    public static let radiusSm: CGFloat = ${parseInt(t.radius.sm)}
    public static let radiusMd: CGFloat = ${parseInt(t.radius.md)}
    public static let radiusLg: CGFloat = ${parseInt(t.radius.lg)}
    public static let gutter: CGFloat = ${parseInt(t.space.gutter)}
    public static let tapMin: CGFloat = ${parseInt(t.space["tap-min"])}
}

extension Color {
    /// A colour that follows the system light/dark appearance. UIKit on iOS; an
    /// AppKit dynamic \`NSColor\` on macOS so LedgerKit's \`swift test\` needs no simulator.
    init(light: (Double, Double, Double), dark: (Double, Double, Double)) {
        #if canImport(UIKit)
        self.init(uiColor: UIColor { traits in
            let c = traits.userInterfaceStyle == .dark ? dark : light
            return UIColor(red: c.0, green: c.1, blue: c.2, alpha: 1)
        })
        #elseif canImport(AppKit)
        self.init(nsColor: NSColor(name: nil) { appearance in
            let isDark = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua
            let c = isDark ? dark : light
            return NSColor(srgbRed: c.0, green: c.1, blue: c.2, alpha: 1)
        })
        #endif
    }
}
`.replace(/public static let cat(\d+)/g, "public static let cat$1");

const chartJs = `// GENERATED by packages/tokens/scripts/build.mjs — edit tokens.json instead.
export const chart = ${JSON.stringify({ light: t.chart.light, dark: t.chart.dark }, null, 2)};
export const categoryTokens = ${JSON.stringify(Object.keys(t.chart.light).filter((k) => k.startsWith("cat-")))};
/** CSS variable for a category colour token, falling back to "uncategorized". */
export const categoryVar = (token) => \`var(--chart-\${token && /^cat-\\d+$/.test(token) ? token : "uncategorized"})\`;
`;

const chartKeys = (o) => Object.keys(o).filter((k) => !k.startsWith("$"));
const chartPalette = (o) => `{\n${chartKeys(o).map((k) => `    ${JSON.stringify(k)}: string;`).join("\n")}\n  }`;
const chartDts = `// GENERATED by packages/tokens/scripts/build.mjs — edit tokens.json instead.
export declare const chart: {
  light: ${chartPalette(t.chart.light)};
  dark: ${chartPalette(t.chart.dark)};
};
/** Category colour tokens, "cat-1" … "cat-${chartKeys(t.chart.light).filter((k) => k.startsWith("cat-")).length}". */
export declare const categoryTokens: string[];
/** CSS variable for a category colour token, falling back to "uncategorized". */
export declare const categoryVar: (token: string | null | undefined) => string;
`;

// [path, content, committed]: committed outputs are tracked in git and drift-checked.
const outputs = [
  [resolve(root, "dist/tokens.css"), css, false],
  [resolve(root, "dist/chart.js"), chartJs, false],
  [resolve(root, "dist/chart.d.ts"), chartDts, false],
  [resolve(root, "../../apps/ios/LedgerKit/Sources/LedgerKit/Theme/Tokens.swift"), swift, true],
];

let stale = false;
for (const [path, content, committed] of outputs) {
  if (check) {
    if (!committed) continue; // generated above in memory; gitignored, rebuilt by `build`
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
      console.error(`stale: ${path} — run 'pnpm --filter @ledger/tokens build' and commit it`);
      stale = true;
    } else {
      console.log(`current ${path}`);
    }
  } else if (existsSync(path) && readFileSync(path, "utf8") === content) {
    console.log(`unchanged ${path}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
